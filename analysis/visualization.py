import os
import matplotlib.pyplot as plt

# Ensure the output directory exists
os.makedirs('visualizations', exist_ok=True)

# Chart 1: Return rate by payment method (descending with labels)

plt.figure(figsize=(7, 5))
pm_order = ['COD', 'UPI', 'CARD']
rates = [44.4, 18.9, 14.7]
colors = ['#d9534f', '#f0ad4e', '#5bc0de']

bars = plt.bar(pm_order, rates, color=colors, edgecolor='black', width=0.5)
plt.title("COD Returns at 44.4% — 3x Card", fontsize=14, fontweight='bold', pad=15)
plt.xlabel("Payment Method", fontsize=11, labelpad=8)
plt.ylabel("Return Rate (%)", fontsize=11, labelpad=8)
plt.ylim(0, 55)

for bar in bars:
    yval = bar.get_height()
    plt.text(bar.get_x() + bar.get_width() / 2.0, yval + 1.0, f"{yval:.1f}%",
             ha='center', va='bottom', fontsize=11, fontweight='bold')

plt.tight_layout()
plt.savefig('visualizations/return_rate_by_payment.png', dpi=300)
plt.show()

# Chart 2: Outlier-corrected monthly revenue trend

plt.figure(figsize=(8, 5))
months = ['2026-01', '2026-02', '2026-03', '2026-04', '2026-05', '2026-06']
revs = [11637.10, 13195.50, 20318.90, 9495.30, 13151.10, 11615.40]

plt.plot(months, revs, marker='o', linewidth=2.5, markersize=8, color='#1f77b4')
plt.title("Outlier-Corrected Revenue: March Genuine Peak at INR 20,318.90", fontsize=13, fontweight='bold', pad=15)
plt.xlabel("Month", fontsize=11, labelpad=8)
plt.ylabel("Order Value (INR)", fontsize=11, labelpad=8)
plt.ylim(0, 24000)

for x, y in zip(months, revs):
    weight = 'bold' if y == max(revs) else 'normal'
    plt.text(x, y + 600, f"INR {y:,.2f}", ha='center', va='bottom', fontsize=9.5, fontweight=weight)

plt.tight_layout()
plt.savefig('visualizations/monthly_revenue_trend.png', dpi=300)
plt.show()