import pandas as pd

orders = pd.read_csv('orders.csv')
products = pd.read_csv('products.csv')
customers = pd.read_csv('customers.csv')

# Verify shapes
print(f"orders.shape: {orders.shape}")
print(f"products.shape: {products.shape}")
print(f"customers.shape: {customers.shape}")

# Task 2 — Standardize payment_method casing

# Verify the 7 distinct raw values before cleaning
raw_unique = orders['payment_method'].unique()
print(f"Unique payment_method before ({len(raw_unique)}): {raw_unique.tolist()}")

# Apply strip and uppercase
orders['payment_method'] = orders['payment_method'].str.strip().str.upper()

# Verify counts after cleaning (Expected: CARD: 70, UPI: 55, COD: 55)
counts = orders['payment_method'].value_counts()
print("\nCounts after standardization:")
print(f"CARD: {counts.get('CARD', 0)}, UPI: {counts.get('UPI', 0)}, COD: {counts.get('COD', 0)}")

# Task 3 — Remove duplicate orders
print("--- Task 3: Remove duplicate orders ---")

# Define natural key (all columns except order_id)
natural_key = [
    'customer_id', 'product_id', 'order_date', 'quantity',
    'discount_pct', 'payment_method', 'rating', 'returned'
]

# Identify duplicates
dup_mask = orders.duplicated(subset=natural_key, keep='first')
dropped_orders = orders[dup_mask]
dropped_order_ids = dropped_orders['order_id'].tolist()

# Print dropped IDs
print(f"Dropped order_id values ({len(dropped_order_ids)} rows): {dropped_order_ids}")

# Drop duplicates
orders_clean = orders.drop_duplicates(subset=natural_key, keep='first').copy()
print(f"orders_clean.shape: {orders_clean.shape}")

# Task 4 — Impute missing values
print("--- Task 4: Impute missing values ---")

# discount_pct: fill NaN with 0 (12 rows affected on deduplicated frame)
nan_discount_count = orders_clean['discount_pct'].isnull().sum()
orders_clean['discount_pct'] = orders_clean['discount_pct'].fillna(0)
print(f"discount_pct NaN filled with 0: {nan_discount_count} rows affected")

# rating: fill NaN with median of non-null ratings (15 rows affected)
median_rating = orders_clean['rating'].median()
nan_rating_count = orders_clean['rating'].isnull().sum()
print(f"Median rating before imputing: {median_rating}")

orders_clean['rating'] = orders_clean['rating'].fillna(median_rating)
print(f"rating NaN filled with median: {nan_rating_count} rows affected")

# Check remaining nulls
print(f"Null counts after imputing: {orders_clean[['discount_pct', 'rating']].isnull().sum().to_dict()}")

print("--- Task 5: Merge and reconcile against Part 1 ---")

# Merge cleaned orders (named merged_clean so Tasks 6-10 work unchanged)
merged_clean = (orders_clean.merge(products, on='product_id', how='left')
                            .merge(customers, on='customer_id', how='left'))
assert merged_clean.shape[0] == 175

merged_clean['order_value'] = (merged_clean['quantity'] * merged_clean['price']
                               * (1 - merged_clean['discount_pct'] / 100))
total_clean = round(merged_clean['order_value'].sum(), 2)
print(f"Cleaned total order_value (175 rows): {total_clean:.2f}")

# Independent sum of the 5 dropped duplicates
dups = dropped_orders.merge(products, on='product_id', how='left')
dups['discount_pct'] = dups['discount_pct'].fillna(0)
dups_value = round((dups['quantity'] * dups['price'] * (1 - dups['discount_pct'] / 100)).sum(), 2)
print(f"Dropped duplicates total order_value: {dups_value:.2f}")

# Raw 180-row total, computed from the data (NaN discount = no promo)
raw = pd.concat([orders_clean, dropped_orders]).merge(products, on='product_id', how='left')
raw['discount_pct'] = raw['discount_pct'].fillna(0)
raw_total = round((raw['quantity'] * raw['price'] * (1 - raw['discount_pct'] / 100)).sum(), 2)
delta = round(raw_total - total_clean, 2)
print(f"Raw total: {raw_total:.2f} | Delta: {delta:.2f}")

assert total_clean == 97358.30
assert raw_total == 99860.20
assert delta == dups_value == 2501.90

print(f"""
RECONCILIATION NOTE: Part 1 Report (a)'s raw total of Rs.{raw_total:,.2f} differs from the cleaned
total of Rs.{total_clean:,.2f} (175 rows) by Rs.{delta:,.2f}. That delta is entirely attributable to the
5 duplicate (double-submit) rows removed in Task 3 ({', '.join(dropped_orders['order_id'])}), whose
independently summed order_value is Rs.{dups_value:,.2f}. Imputation contributes Rs.0.00: missing
discount_pct became 0 (no promo, the same pricing the raw total already used), and rating is not an
input to order_value.
""")

# Task 6 — IQR outlier detection on quantity
print("--- Task 6: IQR outlier detection on quantity ---")

# Compute IQR bounds on quantity
q1 = float(merged_clean['quantity'].quantile(0.25))
q3 = float(merged_clean['quantity'].quantile(0.75))
iqr = q3 - q1
lower = q1 - 1.5 * iqr
upper = q3 + 1.5 * iqr

print(f"Q1 = {q1}, Q3 = {q3}, IQR = {iqr}, lower = {lower}, upper = {upper}")
assert q1 == 1.0 and q3 == 2.0 and iqr == 1.0 and lower == -0.5 and upper == 3.5

# Filter and flag outliers outside [lower, upper]
outliers = merged_clean[(merged_clean['quantity'] < lower) | (merged_clean['quantity'] > upper)]
print(f"Number of outlier rows detected: {len(outliers)}")
for _, row in outliers.iterrows():
    print(f"Outlier detected: {row['order_id']} (quantity: {int(row['quantity'])})")

assert len(outliers) == 2
assert set(outliers['order_id']) == {'O0011', 'O0098'}

# Flag them with a boolean column without dropping (to be used in Task 9 & Task 10)
merged_clean['is_outlier'] = (merged_clean['quantity'] < lower) | (merged_clean['quantity'] > upper)
print(f"is_outlier column created: {merged_clean['is_outlier'].sum()} rows flagged True.")

# Task 7 — Hypothesis: does COD have a higher return rate?
print("--- Task 7: Hypothesis: does COD have a higher return rate? ---")

# Explicit statement of hypothesis
print("Hypothesis: Cash on Delivery (COD) orders exhibit a significantly higher return rate than Card and UPI orders.")

# Aggregate return count and mean return rate by payment_method
pm_returns = merged_clean.groupby('payment_method')['returned'].agg(['count', 'mean'])
print("\nReturn rates by payment method:")
print(pm_returns)

print("\nRounded return rates:")
for pm, row in pm_returns.iterrows():
    print(f"  {pm}: {row['mean'] * 100:.1f}% ({int(row['count'])} orders)")

# Assert expected rounded values
assert round(pm_returns.loc['CARD', 'mean'] * 100, 1) == 14.7
assert round(pm_returns.loc['COD', 'mean'] * 100, 1) == 44.4
assert round(pm_returns.loc['UPI', 'mean'] * 100, 1) == 18.9

print("\nHypothesis Verdict: Confirmed")

# Task 8 — Multi-level segmentation
print("--- Task 8: Multi-level segmentation ---")

# Group by payment_method and city_tier
seg_returns = merged_clean.groupby(['payment_method', 'city_tier'])['returned'].agg(['count', 'mean'])
print("Segment Breakdown (count and return rate):")
print(seg_returns)

# Detailed breakdown formatted as percentages
print("\nFormatted Return Rates:")
for (pm, tier), row in seg_returns.iterrows():
    print(f"  {pm} + Tier-{tier}: {row['mean'] * 100:.1f}% ({int(row['count'])} orders)")

# Assert specific figures required by task
assert int(seg_returns.loc[('COD', 1), 'count']) == 32
assert round(seg_returns.loc[('COD', 1), 'mean'] * 100, 1) == 37.5

assert int(seg_returns.loc[('COD', 2), 'count']) == 22
assert round(seg_returns.loc[('COD', 2), 'mean'] * 100, 1) == 54.5

print("\n--- Key Finding ---")
print("Single highest-risk segment: COD + Tier-2 cities at 54.5% (32 Tier-1 COD orders at 37.5%, versus 22 Tier-2 COD orders at 54.5%).")
print("Insight: COD risk is not uniform across tiers; a single blended rate masks that return risk is heavily concentrated in Tier-2 COD orders.")

# Task 9 — Correlation analysis
print("--- Task 9: Correlation analysis ---")

corr_cols = ['rating', 'returned', 'discount_pct', 'quantity']
corr_matrix = merged_clean[corr_cols].corr()

print("Correlation Matrix:")
print(corr_matrix.round(4))

def get_band(r):
    val = abs(r)
    if val < 0.2:
        return "negligible"
    elif val < 0.4:
        return "weak"
    elif val < 0.7:
        return "moderate"
    else:
        return "strong"

print("\nPairwise Correlation Band Classification:")
print("Bands: 0–0.19 negligible | 0.2–0.39 weak | 0.4–0.69 moderate | 0.7–1.0 strong")

pairs = [
    ('rating', 'returned'),
    ('rating', 'discount_pct'),
    ('rating', 'quantity'),
    ('returned', 'discount_pct'),
    ('returned', 'quantity'),
    ('discount_pct', 'quantity')
]

for col1, col2 in pairs:
    r_val = corr_matrix.loc[col1, col2]
    band = get_band(r_val)
    print(f"  {col1} vs {col2}: r = {r_val:.4f} -> {band} (|r| < 0.2)")
    assert abs(r_val) < 0.2

disc_ret_corr = corr_matrix.loc['discount_pct', 'returned']
print(f"\nHypothesis 'higher discounts reduce returns' (discount_pct vs returned r = {disc_ret_corr:.4f}): Busted")

# Task 10 — Outlier-corrected time series
print("--- Task 10: Outlier-corrected time series ---")

# Convert order_date to datetime and extract year-month
merged_clean['year_month'] = pd.to_datetime(merged_clean['order_date']).dt.to_period('M').astype(str)

# (1) Monthly total order_value including the two Task 6 outlier orders
monthly_with_outliers = merged_clean.groupby('year_month')['order_value'].sum()

# (2) Monthly total order_value excluding the two Task 6 outlier orders
monthly_no_outliers = merged_clean[~merged_clean['is_outlier']].groupby('year_month')['order_value'].sum()

print("Monthly revenue (1) Including outliers:")
for ym, val in monthly_with_outliers.items():
    print(f"  {ym}: {val:.2f}")

print("\nMonthly revenue (2) Outlier-corrected (excluding outliers):")
for ym, val in monthly_no_outliers.items():
    print(f"  {ym}: {val:.2f}")

# Assert expected values
assert round(monthly_with_outliers['2026-01'], 2) == 29582.10
assert round(monthly_no_outliers['2026-01'], 2) == 11637.10
assert round(monthly_no_outliers['2026-02'], 2) == 13195.50
assert round(monthly_no_outliers['2026-03'], 2) == 20318.90
assert round(monthly_no_outliers['2026-04'], 2) == 9495.30
assert round(monthly_no_outliers['2026-05'], 2) == 13151.10
assert round(monthly_no_outliers['2026-06'], 2) == 11615.40

print("\n--- Key Finding ---")
print("January's apparent lead (₹29,582.10) is an artifact of the two bulk orders landing in January "
      "(O0011 on 2026-01-28, O0098 on 2026-01-10). Once excluded, March is the genuine peak month "
      "(₹20,318.90) — demonstrating why outlier detection in Task 6 must precede monthly trend analysis.")